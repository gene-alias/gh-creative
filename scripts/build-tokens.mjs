import fs from 'node:fs';
const source = JSON.parse(fs.readFileSync('design-system/tokens.json', 'utf8'));
const flat = new Map();
function walk(node, path = []) {
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    const p = [...path, key];
    if (value && '$value' in value) flat.set(p.join('.'), value);
    else walk(value, p);
  }
}
walk(source);
const name = (path) =>
  '--gh-' +
  path
    .replace(/^primitive\./, 'ref.')
    .replace(/^(semantic|component)\./, '')
    .replaceAll('.', '-');
const names = new Set();
function resolve(path, trail = []) {
  if (trail.includes(path))
    throw Error('Circular token: ' + [...trail, path].join(' → '));
  const token = flat.get(path);
  if (!token) throw Error('Missing token: ' + path);
  const match = String(token.$value).match(/^\{(.+)\}$/);
  return match ? resolve(match[1], [...trail, path]) : token.$value;
}
let css =
  '/* Generated by scripts/build-tokens.mjs. Edit tokens.json, not this file. */\n:root {\n';
for (const [path, token] of flat) {
  resolve(path);
  if (names.has(name(path))) throw Error('CSS name collision: ' + path);
  names.add(name(path));
  let value = String(token.$value).replace(
    /\{([^}]+)\}/g,
    (_, ref) => 'var(' + name(ref) + ')',
  );
  css += `  /* ${token.$description} */\n  ${name(path)}: ${value};\n`;
}
css +=
  '}\n@media (max-width: 359px) {\n  :root { --gh-gutter: var(--gh-ref-space-5); --gh-section-space: var(--gh-ref-space-16); }\n}\n@media (prefers-reduced-motion: reduce) {\n  :root { --gh-motion-fast: 0ms; --gh-motion-normal: 0ms; }\n}\n';
fs.writeFileSync('design-system/tokens.css', css);
fs.mkdirSync('public/design-system', { recursive: true });
fs.writeFileSync('public/design-system/tokens.css', css);
fs.copyFileSync(
  'design-system/tokens.json',
  'public/design-system/tokens.json',
);
const luminance = (hex) => {
  const v = hex
    .slice(1)
    .match(/../g)
    .map((v) => parseInt(v, 16) / 255)
    .map((v) => (v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return v[0] * 0.2126 + v[1] * 0.7152 + v[2] * 0.0722;
};
function ratio(a, b) {
  const x = luminance(a),
    y = luminance(b);
  return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05);
}
const checks = [
  ['Primary text', 'text-primary', 'surface-canvas', 4.5],
  ['Secondary text', 'text-secondary', 'surface-canvas', 4.5],
  ['Accent text', 'accent', 'surface-canvas', 4.5],
  ['Button label', 'text-on-accent', 'accent', 4.5],
  ['Pressed button label', 'text-on-accent', 'accent-pressed', 4.5],
  ['Field boundary', 'border-control', 'surface-panel', 3],
  ['Focus ring', 'focus', 'surface-panel', 3],
  ['Error message', 'feedback-error', 'surface-panel', 4.5],
].map(([label, a, b, min]) => {
  const result = ratio(resolve('semantic.' + a), resolve('semantic.' + b));
  if (result < min) throw Error(`${label}: ${result.toFixed(2)} < ${min}`);
  return { label, ratio: result.toFixed(2) + ':1', minimum: min + ':1' };
});
fs.writeFileSync(
  'design-system/validation.json',
  JSON.stringify({ tokenCount: flat.size, checks }, null, 2) + '\n',
);
console.log(
  `Generated ${flat.size} tokens. Aliases, names and ${checks.length} contrast pairs pass.`,
);
